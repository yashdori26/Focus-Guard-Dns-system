  /// Resolves an app definition by Android package name.
  static AppDefinition? findByPackage(String packageName) {
    final lower = packageName.toLowerCase();
    for (final def in allDefinitions) {
      if (def.primaryPackage.toLowerCase() == lower) return def;
      for (final sec in def.secondaryPackages) {
        if (sec.toLowerCase() == lower) return def;
      }
    }
    return null;
  }

  /// Resolves an app definition by network domain or hostname.
  static AppDefinition? findByDomain(String domain) {
    final lower = domain.toLowerCase();
    for (final def in allDefinitions) {
      for (final d in def.networkDomains) {
        if (lower == d || lower.endsWith('.$d')) return def;
      }
      for (final c in def.cdnDomains) {
        if (lower == c || lower.endsWith('.$c')) return def;
      }
    }
    return null;
  }
